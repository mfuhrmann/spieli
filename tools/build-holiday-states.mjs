#!/usr/bin/env node
// Extracts the state codes and names the opening_hours library knows for its
// state-specific holidays, into app/src/lib/holidayStates.generated.json
// (#878). The library keys those holidays on the full state name and does not
// export its definitions, so REGION_STATE codes ("he", "DE-HE") are resolved
// to names from this table instead of through library internals.
//
// Run via `make holiday-states` after bumping opening_hours; a unit test fails
// while the table's recorded version differs from the installed one.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import vm from 'node:vm';

const require = createRequire(new URL('../app/package.json', import.meta.url));
const pkgPath = require.resolve('opening_hours/package.json');
const { version } = JSON.parse(readFileSync(pkgPath, 'utf8'));
const buildPath = pkgPath.replace(/package\.json$/, 'build/opening_hours.js');

const MARKER = 'var holiday_definitions = ';
const src = readFileSync(buildPath, 'utf8');
if (!src.includes(MARKER)) throw new Error(`${MARKER.trim()} not found in ${buildPath}: the build layout changed`);
const sandbox = { module: { exports: {} }, exports: {}, require, console, globalThis: {} };
sandbox.globalThis = sandbox;
vm.runInNewContext(src.replace(MARKER, `${MARKER}globalThis.__defs = `), sandbox, { filename: buildPath });
const defs = sandbox.__defs;
if (!defs?.de) throw new Error('holiday definitions not captured');

const out = { _comment: 'Generated by tools/build-holiday-states.mjs — do not edit.', opening_hours: version, countries: {} };
for (const [cc, country] of Object.entries(defs)) {
  if (cc.startsWith('_') || typeof country !== 'object' || country === null) continue;
  const codes = {};
  const names = [];
  for (const [name, def] of Object.entries(country)) {
    if (name.startsWith('_') || typeof def !== 'object' || def === null || Array.isArray(def)) continue;
    // A state entry carries its own holiday lists; the country-wide entries
    // ("PH", "SH") are arrays and skipped above.
    names.push(name);
    if (typeof def._state_code === 'string') codes[def._state_code.toLowerCase()] = name;
  }
  if (names.length) out.countries[cc] = { codes, names: names.sort() };
}

const target = new URL('../app/src/lib/holidayStates.generated.json', import.meta.url);
writeFileSync(target, JSON.stringify(out, null, 1) + '\n');
console.log(`wrote ${Object.keys(out.countries).length} countries (opening_hours ${version})`);
